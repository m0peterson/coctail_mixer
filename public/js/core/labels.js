/** Какие инструменты понадобятся. */
export function toolsFor(cocktail) {
  const tools = [];
  const { method, flags = [] } = cocktail;
  if (method === 'shake') tools.push('шейкер (или банка с крышкой)', 'ситечко');
  if (method === 'stir') tools.push('стакан для смешивания', 'барная ложка', 'ситечко');
  if (method === 'blend') tools.push('блендер');
  if (method === 'layer') tools.push('барная ложка');
  if (method === 'hot') tools.push('кастрюля или чайник');
  if (flags.includes('muddle')) tools.push('мадлер или скалка');
  tools.push('джиггер или мерный стаканчик');
  return tools;
}
